-- Tabela original, criada antes pelo Hibernate (ddl-auto=update).
-- "if not exists" permite rodar tanto em banco novo quanto no banco que já existia.
create table if not exists tb_customers (
    id         bigint generated by default as identity primary key,
    name       varchar(255),
    email      varchar(255) unique,
    phone      varchar(255),
    status     varchar(255),
    created_at timestamp(6)
);
