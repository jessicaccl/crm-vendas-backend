-- E-mail do cliente passa a ser único dentro da organização (não no sistema todo).
-- O nome da restrição antiga varia conforme quem criou a tabela, então ela é procurada pelo catálogo.
do $$
declare
    constraint_name text;
begin
    for constraint_name in
        select con.conname
          from pg_constraint con
          join pg_attribute att on att.attrelid = con.conrelid and att.attnum = any (con.conkey)
         where con.conrelid = 'tb_customers'::regclass
           and con.contype = 'u'
           and att.attname = 'email'
           and array_length(con.conkey, 1) = 1
    loop
        execute format('alter table tb_customers drop constraint %I', constraint_name);
    end loop;
end $$;

alter table tb_customers add constraint uk_customers_org_email unique (organization_id, email);

