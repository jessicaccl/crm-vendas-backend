-- Multiempresa: cada usuário, cliente, negócio e lead recebido pertence a uma organização.
-- Os dados que já existiam vão para a organização "Demo".

create table tb_organizations (
    id                     bigint generated by default as identity primary key,
    name                   varchar(120) not null,
    slug                   varchar(60)  not null unique,
    demo                   boolean      not null default false,
    netlify_webhook_secret varchar(100),
    created_at             timestamptz  not null default now()
);

insert into tb_organizations (name, slug, demo) values ('Demo CRM Pro', 'demo', true);

alter table tb_users         add column organization_id bigint references tb_organizations (id);
alter table tb_customers     add column organization_id bigint references tb_organizations (id);
alter table tb_deals         add column organization_id bigint references tb_organizations (id);
alter table tb_inbound_leads add column organization_id bigint references tb_organizations (id);

