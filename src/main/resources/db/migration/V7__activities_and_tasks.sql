-- Ficha do cliente: atividades registradas (anotações, ligações...) e tarefas com prazo.

create table tb_activities (
    id              bigint generated by default as identity primary key,
    organization_id bigint      not null references tb_organizations (id),
    customer_id     bigint      not null references tb_customers (id) on delete cascade,
    deal_id         bigint      references tb_deals (id) on delete set null,
    type            varchar(20) not null check (type in ('NOTE', 'CALL', 'WHATSAPP', 'EMAIL', 'MEETING')),
    content         text        not null,
    author_name     varchar(120),
    created_at      timestamptz not null
);

create index idx_activities_customer on tb_activities (organization_id, customer_id, created_at desc);

create table tb_tasks (
    id              bigint generated by default as identity primary key,
    organization_id bigint       not null references tb_organizations (id),
    customer_id     bigint       references tb_customers (id) on delete cascade,
    deal_id         bigint       references tb_deals (id) on delete set null,
    title           varchar(200) not null,
    due_at          timestamptz  not null,
    done_at         timestamptz,
    created_at      timestamptz  not null,
    updated_at      timestamptz  not null
);

create index idx_tasks_org_due on tb_tasks (organization_id, done_at, due_at);
create index idx_tasks_customer on tb_tasks (customer_id);
create index idx_tasks_deal on tb_tasks (deal_id);
