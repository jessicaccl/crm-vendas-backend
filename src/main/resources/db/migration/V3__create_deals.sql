-- Negócios (oportunidades de venda) e o histórico de mudanças de etapa do funil.

create table tb_deals (
    id                  bigint generated by default as identity primary key,
    title               varchar(150)   not null,
    value               numeric(14, 2) not null default 0 check (value >= 0),
    stage               varchar(20)    not null
        check (stage in ('PROSPECT', 'QUALIFIED', 'PROPOSAL', 'WON', 'LOST')),
    source              varchar(20)
        check (source in ('REFERRAL', 'INSTAGRAM', 'WEBSITE', 'WHATSAPP', 'OTHER')),
    expected_close_date date,
    lost_reason         varchar(255),
    customer_id         bigint         not null references tb_customers (id),
    stage_changed_at    timestamptz    not null,
    closed_at           timestamptz,
    created_at          timestamptz    not null,
    updated_at          timestamptz    not null
);

create index idx_deals_stage on tb_deals (stage);
create index idx_deals_customer on tb_deals (customer_id);

create table tb_deal_stage_changes (
    id         bigint generated by default as identity primary key,
    deal_id    bigint      not null references tb_deals (id) on delete cascade,
    from_stage varchar(20),
    to_stage   varchar(20) not null,
    changed_at timestamptz not null
);

create index idx_stage_changes_deal on tb_deal_stage_changes (deal_id);
