-- Observações livres no negócio (ex.: resultado e placar do diagnóstico)
alter table tb_deals add column notes text;

-- Registro de cada lead recebido de fora (auditoria e proteção contra reenvio)
create table tb_inbound_leads (
    id          bigint generated by default as identity primary key,
    provider    varchar(30)  not null,
    external_id varchar(100) not null,
    form_name   varchar(100),
    payload     jsonb        not null,
    customer_id bigint       references tb_customers (id) on delete set null,
    deal_id     bigint       references tb_deals (id) on delete set null,
    received_at timestamptz  not null,
    constraint uk_inbound_leads_external unique (provider, external_id)
);

create index idx_inbound_leads_received on tb_inbound_leads (received_at desc);
